import { build } from 'esbuild';
import { writeFileSync, existsSync } from 'node:fs';
for (const file of ['.env', '.env.local']) if (existsSync(file)) process.loadEnvFile(file);
if (process.env.NEON_AUTH_BASE_URL && process.env.NEON_DATA_API_URL) {
  const config = { authUrl: process.env.NEON_AUTH_BASE_URL, dataApiUrl: process.env.NEON_DATA_API_URL, prospectSearchUrl: process.env.NEON_PROSPECT_SEARCH_URL || '' };
  for (const value of Object.values(config).filter(Boolean)) {
    const url = new URL(value);
    if (url.protocol !== 'https:' || url.username || url.password || url.search || url.hash) throw new Error('Endpoint público inválido.');
  }
  writeFileSync('neon-config.js', '// Public endpoints only. Generated by npm run build.\nwindow.NEON_CONFIG = Object.freeze(' + JSON.stringify(config, null, 2) + ');\n');
}
await build({ entryPoints: ['src/neon-client.js'], bundle: true, format: 'iife', platform: 'browser', target: ['es2022'], outfile: 'assets/neon-client.js', minify: true, legalComments: 'eof' });
